using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

[CustomEditor(typeof(ViewBase), true, isFallback = true)]
public sealed class ReferenceHolderEditor : Editor
{
    private const string Header = "// <auto-generated by ReferenceHolder>";
    private const string GeneratedDirectory = "Assets\\Scripts\\Gen";
    private ViewBase Destination => (ViewBase)target;

    private sealed class Entry
    {
        public string name;
        public UnityEngine.Object value;
    }

    public override void OnInspectorGUI()
    {
        DrawDefaultInspector();
        EditorGUILayout.Space();
        var holder = Destination.GetComponent<ReferenceHolder>();
        EditorGUILayout.HelpBox("生成私有缓存字段和 BindReferences；Awake 中从 Holder 获取一次，不再序列化或同步 View 引用。输出：Assets/Scripts/Gen。", MessageType.Info);
        if (holder == null)
            EditorGUILayout.HelpBox("当前物体缺少 ReferenceHolder。", MessageType.Warning);
        using (new EditorGUI.DisabledScope(holder == null || EditorApplication.isCompiling || EditorApplication.isPlaying))
        {
            if (GUILayout.Button("生成引用代码")) RunSafely(Generate);
        }
    }

    private static List<Entry> ReadEntries(ReferenceHolder holder)
    {
        var source = new SerializedObject(holder);
        source.Update();
        var dictionary = source.FindProperty("references");
        var keys = dictionary.FindPropertyRelative("m_keys");
        var values = dictionary.FindPropertyRelative("m_values");
        if (keys.arraySize != values.arraySize) throw new InvalidOperationException("引用表结构不一致。");
        var entries = new List<Entry>();
        var names = new HashSet<string>(StringComparer.Ordinal);
        for (int i = 0; i < keys.arraySize; i++)
        {
            var name = keys.GetArrayElementAtIndex(i).stringValue;
            var value = values.GetArrayElementAtIndex(i).objectReferenceValue;
            if (string.IsNullOrEmpty(name) || !Regex.IsMatch(name, @"^[A-Za-z_][A-Za-z0-9_]*$") || !names.Add(name))
                throw new InvalidOperationException("名称必须是唯一的标识符（字母、数字、下划线）：" + name);
            if (value == null) throw new InvalidOperationException("引用为空：" + name);
            var type = value.GetType();
            if (!type.IsVisible || type.IsNested || type.IsGenericType)
                throw new InvalidOperationException("不支持非公开、嵌套或泛型引用类型：" + type);
            entries.Add(new Entry { name = name, value = value });
        }
        return entries;
    }

    private void Generate()
    {
        var destination = Destination;
        var holder = destination.GetComponent<ReferenceHolder>();
        if (holder == null)
            throw new InvalidOperationException("View 同物体上必须有 ReferenceHolder。");
        var type = destination.GetType();
        var script = MonoScript.FromMonoBehaviour(destination);
        var sourcePath = AssetDatabase.GetAssetPath(script);
        if (!sourcePath.StartsWith("Assets/", StringComparison.Ordinal) || type.IsNested || type.IsGenericType || !type.IsPublic ||
            !Regex.IsMatch(script.text, @"\bpublic\s+partial\s+class\s+" + Regex.Escape(type.Name) + @"\b"))
            throw new InvalidOperationException("目标脚本须在 Assets 内，声明为 public partial class；不支持嵌套和泛型类。");
        var entries = ReadEntries(holder);
        var assemblyName = UnityEditor.Compilation.CompilationPipeline.GetAssemblyNameFromScriptPath(sourcePath);
        if (Path.GetFileNameWithoutExtension(assemblyName) != "Assembly-CSharp")
            throw new InvalidOperationException("统一生成目录仅支持 Assembly-CSharp 中的 View，partial 类不能跨程序集。");
        var path = Path.Combine(GeneratedDirectory, type.FullName + ".References.g.cs");
        var previousCode = File.Exists(path) ? File.ReadAllText(path) : "";
        if (previousCode.Length > 0 && !previousCode.StartsWith(Header, StringComparison.Ordinal))
            throw new InvalidOperationException("拒绝覆盖非生成文件：" + path);
        var code = new StringBuilder(Header + "\n");
        if (!string.IsNullOrEmpty(type.Namespace)) code.AppendLine("namespace " + type.Namespace + " {");
        code.AppendLine("public partial class " + type.Name + " {");
        foreach (var entry in entries)
        {
            var flags = BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;
            bool generated = Regex.IsMatch(previousCode, @"\bprivate\s+global::[\w.]+\s+@?" + Regex.Escape(entry.name) + @"\s*;");
            if (entry.name == type.Name || entry.name == "BindReferences" || entry.name == "referenceHolder" ||
                (type.GetMember(entry.name, flags).Length > 0 && !generated))
                throw new InvalidOperationException("名称与现有成员冲突：" + entry.name);
            code.AppendLine("    private global::" + entry.value.GetType().FullName + " @" + entry.name + ";");
        }
        code.AppendLine();
        code.AppendLine("    protected override void BindReferences()");
        code.AppendLine("    {");
        code.AppendLine("        base.BindReferences();");
        foreach (var entry in entries)
            code.AppendLine("        @" + entry.name + " = referenceHolder.Get<global::" + entry.value.GetType().FullName + ">(" + "\"" + entry.name + "\");");
        code.AppendLine("    }");
        code.AppendLine("}");
        if (!string.IsNullOrEmpty(type.Namespace)) code.AppendLine("}");
        Directory.CreateDirectory(GeneratedDirectory);
        if (previousCode != code.ToString())
        {
            File.WriteAllText(path, code.ToString(), new UTF8Encoding(false));
            AssetDatabase.Refresh();
        }
        Debug.Log("View 引用代码已生成；运行时在 Awake 中绑定：" + type.Name, destination);
    }

    private static void RunSafely(Action action)
    {
        try { action(); }
        catch (Exception exception) { Debug.LogError("ReferenceHolder: " + exception.Message); }
    }
}